// The dependency update configuration (docs/design.md §11, §20), which
// only the Go core writes: .github/dependabot.yml with an "updates" entry
// per package ecosystem and directory, and renovate.json enabling the
// managers of the project's languages for their components' directories.
// Each definition names its Dependabot ecosystems ("dependabot") and
// Renovate managers ("renovate").

// RenovateSchema is the schema renovate.json names.
const RenovateSchema = "https://docs.renovatebot.com/renovate-schema.json"

// updateEntry is one Dependabot "updates" entry before the project's settings.
type updateEntry struct {
	ecosystem, directory string
}

// dependabotUpdates are the project's entries: for each language and each
// component's directory, the ecosystems whose files are there; then
// github-actions at the root when there are GitHub workflows.
func dependabotUpdates(p *project.Project, githubActions bool) ([]updateEntry, error) {
	var updates []updateEntry
	seen := map[updateEntry]bool{}
	add := func(u updateEntry) {
		if !seen[u] {
			seen[u] = true
			updates = append(updates, u)
		}
	}
	for _, lang := range p.Languages {
		rules, err := p.DependabotRules(lang)
		if err != nil || len(rules) == 0 {
			if err != nil {
				return nil, err
			}
			continue
		}
		dirs, err := p.ImplDirs(lang)
		if err != nil {
			return nil, err
		}
		for _, dir := range dirs {
			for _, rule := range rules {
				if (len(rule.Files) == 0 || anyFile(dir.Dir, rule.Files)) && !anyFile(dir.Dir, rule.Unless) {
					add(updateEntry{rule.Ecosystem, rootPath(p, dir.Dir)})
				}
			}
		}
	}
	if githubActions {
		add(updateEntry{"github-actions", "/"})
	}
	return updates, nil
}

// rootPath is a directory as Dependabot names it: from the root, with a
// leading slash.
func rootPath(p *project.Project, dir string) string {
	relative := filepath.ToSlash(project.PyRelpath(dir, p.Root))
	if relative == "." {
		return "/"
	}
	return "/" + relative
}

// anyFile reports whether any of the patterns matches a file in dir.
func anyFile(dir string, patterns []string) bool {
	for _, pattern := range patterns {
		if matches, _ := filepath.Glob(filepath.Join(dir, pattern)); len(matches) > 0 {
			return true
		}
	}
	return false
}

// HasGitHubWorkflows reports whether the project's Dependabot
// configuration covers GitHub Actions: it generates GitHub workflows or
// has a .github/workflows directory.
func HasGitHubWorkflows(p *project.Project, generatesGitHub bool) bool {
	info, err := os.Stat(filepath.Join(p.Root, ".github", "workflows"))
	return generatesGitHub || err == nil && info.IsDir()
}

// Dependabot is the project's .github/dependabot.yml: an "updates" entry
// per ecosystem and directory, each with the "dependabot" section's
// settings (a weekly schedule unless they set one) and its ecosystem's.
func Dependabot(p *project.Project, settings project.UpdateSettings, githubActions bool) (string, error) {
	updates, err := dependabotUpdates(p, githubActions)
	if err != nil {
		return "", err
	}
	banner := Banner([]string{
		"Generated by: hecatron workflows (generated.dependabot)",
		"from the project's languages and components",
		"",
		"To update: edit config.json's \"dependabot\", then run",
		"hecatron workflows (hecatron add and remove do too)",
	}, "# ", "")
	lines := []string{strings.TrimRight(banner, "\n"), "", "version: 2"}
	if len(updates) == 0 {
		lines = append(lines, "updates: []")
	} else {
		lines = append(lines, "updates:")
	}
	for _, u := range updates {
		entry := project.NewObject()
		entry.Set("package-ecosystem", u.ecosystem)
		entry.Set("directory", u.directory)
		entry.Set("schedule", weekly())
		mergeInto(entry, settings.DependabotOptions)
		if settings.DependabotEcosystems != nil {
			own, _ := settings.DependabotEcosystems.Values[u.ecosystem].(*project.Object)
			mergeInto(entry, own)
		}
		lines = append(lines, yamlListItem("  ", entry)...)
	}
	return strings.Join(lines, "\n") + "\n", nil
}

func weekly() *project.Object {
	schedule := project.NewObject()
	schedule.Set("interval", "weekly")
	return schedule
}

func mergeInto(dest, from *project.Object) {
	if from == nil {
		return
	}
	for _, key := range from.Keys {
		dest.Set(key, from.Values[key])
	}
}

// Renovate is the project's renovate.json: the "renovate" section's
// settings, then the managers of the project's languages (and
// github-actions) enabled for their components' directories only.
func Renovate(p *project.Project, settings project.UpdateSettings, githubActions bool) (string, error) {
	config := project.NewObject()
	config.Set("$schema", RenovateSchema)
	config.Set("description", []any{
		"DO NOT EDIT: generated by hecatron workflows (generated.renovate) from the project's languages and components.",
		"To update: edit .hecatron/config.json's \"renovate\", then run hecatron workflows (hecatron add and remove do too).",
	})
	mergeInto(config, settings.RenovateOptions)
	var managers, paths []any
	everywhere := false
	for _, lang := range p.Languages {
		names, err := p.RenovateManagers(lang)
		if err != nil {
			return "", err
		}
		dirs, err := p.ImplDirs(lang)
		if err != nil {
			return "", err
		}
		if len(names) == 0 || len(dirs) == 0 {
			continue
		}
		for _, name := range names {
			managers = appendNew(managers, name)
		}
		for _, dir := range dirs {
			if where := rootPath(p, dir.Dir); where == "/" {
				everywhere = true
			} else {
				paths = appendNew(paths, strings.TrimPrefix(where, "/")+"/**")
			}
		}
	}
	if githubActions {
		managers = appendNew(managers, "github-actions")
		paths = appendNew(paths, ".github/workflows/**")
	}
	if managers == nil {
		managers = []any{}
	}
	config.Set("enabledManagers", managers)
	if !everywhere {
		if paths == nil {
			paths = []any{}
		}
		config.Set("includePaths", paths)
	}
	var out bytes.Buffer
	writeJSON(&out, config, "")
	out.WriteString("\n")
	return out.String(), nil
}

func appendNew(list []any, item string) []any {
	for _, entry := range list {
		if entry == item {
			return list
		}
	}
	return append(list, item)
}

// writeJSON writes a decoded value as Python's json.dumps(indent=2,
// ensure_ascii=False) would, keys in their order.
func writeJSON(out *bytes.Buffer, value any, indent string) {
	inner := indent + "  "
	switch v := value.(type) {
	case *project.Object:
		if len(v.Keys) == 0 {
			out.WriteString("{}")
			return
		}
		out.WriteString("{\n")
		for i, key := range v.Keys {
			out.WriteString(inner + jsonString(key) + ": ")
			writeJSON(out, v.Values[key], inner)
			if i < len(v.Keys)-1 {
				out.WriteString(",")
			}
			out.WriteString("\n")
		}
		out.WriteString(indent + "}")
	case []any:
		if len(v) == 0 {
			out.WriteString("[]")
			return
		}
		out.WriteString("[\n")
		for i, item := range v {
			out.WriteString(inner)
			writeJSON(out, item, inner)
			if i < len(v)-1 {
				out.WriteString(",")
			}
			out.WriteString("\n")
		}
		out.WriteString(indent + "]")
	case string:
		out.WriteString(jsonString(v))
	case json.Number:
		out.WriteString(v.String())
	case bool:
		fmt.Fprint(out, v)
	default:
		out.WriteString("null")
	}
}

func jsonString(s string) string {
	var b bytes.Buffer
	encoder := json.NewEncoder(&b)
	encoder.SetEscapeHTML(false)
	_ = encoder.Encode(s)
	return strings.TrimSuffix(b.String(), "\n")
}

// yamlListItem is a mapping as a block list item at indent ("- " then its
// keys).
func yamlListItem(indent string, object *project.Object) []string {
	lines := yamlMapping(indent+"  ", object)
	if len(lines) == 0 {
		return []string{indent + "- {}"}
	}
	lines[0] = indent + "- " + strings.TrimPrefix(lines[0], indent+"  ")
	return lines
}

// yamlMapping is a mapping's keys in block style at indent.
func yamlMapping(indent string, object *project.Object) []string {
	var lines []string
	for _, key := range object.Keys {
		prefix := indent + yamlScalar(key) + ":"
		switch v := object.Values[key].(type) {
		case *project.Object:
			if len(v.Keys) == 0 {
				lines = append(lines, prefix+" {}")
				continue
			}
			lines = append(lines, prefix)
			lines = append(lines, yamlMapping(indent+"  ", v)...)
		case []any:
			if len(v) == 0 {
				lines = append(lines, prefix+" []")
				continue
			}
			lines = append(lines, prefix)
			for _, item := range v {
				if object, ok := item.(*project.Object); ok {
					lines = append(lines, yamlListItem(indent+"  ", object)...)
				} else if list, ok := item.([]any); ok {
					lines = append(lines, indent+"  - "+yamlFlow(list))
				} else {
					lines = append(lines, indent+"  - "+yamlValue(item))
				}
			}
		default:
			lines = append(lines, prefix+" "+yamlValue(v))
		}
	}
	return lines
}

// yamlValue is a scalar: strings as yamlScalar, numbers and booleans as
// JSON writes them.
func yamlValue(value any) string {
	switch v := value.(type) {
	case string:
		return yamlScalar(v)
	case json.Number:
		return v.String()
	case bool:
		return fmt.Sprint(v)
	case nil:
		return "null"
	}
	return compactJSON(value)
}

// yamlFlow is a nested list in flow style, which compact JSON is.
func yamlFlow(list []any) string { return compactJSON(list) }

func compactJSON(value any) string {
	var b, compact bytes.Buffer
	writeJSON(&b, value, "")
	_ = json.Compact(&compact, b.Bytes())
	return compact.String()
}
