#!/usr/bin/env python3
"""The language x platform coverage matrix.

    matrix.py collect --commit SHA LOG...   add the "### coverage {json}" lines
                                            tests/install/check.sh printed in
                                            LOGs to results.json (newest wins)
    matrix.py render                        write docs/coverage.md from it

results.json holds one result per language and platform. "evidence" says how
it was obtained: "fresh" is check.sh on a fresh machine or container;
"in-use" is a developer machine whose toolchains were installed over time,
where the project's tests pass but a from-scratch install wasn't checked.
"""

from __future__ import annotations

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
RESULTS = os.path.join(HERE, "results.json")
DOC = os.path.join(ROOT, "docs", "coverage.md")

PLATFORMS = [
    ("linux-x86_64-ubuntu24.04", "Ubuntu 24.04 x86_64"),
    ("linux-x86_64-ubuntu26.04", "Ubuntu 26.04 x86_64"),
    ("linux-x86_64-debian13", "Debian 13 x86_64"),
    ("linux-aarch64-ubuntu24.04", "Ubuntu 24.04 arm64"),
    ("linux-aarch64-ubuntu26.04", "Ubuntu 26.04 arm64"),
    ("linux-aarch64-debian13", "Debian 13 arm64"),
    ("macos-aarch64", "macOS arm64"),
    ("macos-x86_64", "macOS x86_64"),
]

# Each status, in the order the totals list them, and what it means.
MARKS = [
    ("✅", "Installs on a fresh machine, passes `doctor` (also from a new shell), reinstalls cleanly, and passes its smoke test (builds and runs a small program)"),
    ("💻", "Works on a developer machine (`doctor` and the project's tests pass), but a fresh install wasn't checked"),
    ("❌", "Fails"),
    ("➖", "No toolchain exists for this platform upstream"),
    ("❔", "Not checked yet, or not since the language's smoke test was added"),
]
LEGEND = "| Status | Meaning |\n| --- | --- |\n" + "\n".join(f"| {mark} | {meaning} |" for mark, meaning in MARKS)


def load() -> dict[str, dict]:
    if not os.path.exists(RESULTS):
        return {}
    with open(RESULTS) as f:
        return {f"{r['language']} {r['platform']}": r for r in json.load(f)}


def save(results: dict[str, dict]) -> None:
    ordered = sorted(results.values(), key=lambda r: (r["language"], r["platform"]))
    with open(RESULTS, "w") as f:
        json.dump(ordered, f, indent=1, ensure_ascii=False)
        f.write("\n")


def collect(commit: str, logs: list[str]) -> None:
    results = load()
    for log in logs:
        with open(log, errors="replace") as f:
            for line in f:
                if line.startswith("### coverage "):
                    result = json.loads(line[len("### coverage "):])
                    result["commit"] = commit
                    results[f"{result['language']} {result['platform']}"] = result
    save(results)


def mark(result: dict | None) -> str:
    if result is None:
        return "❔"
    steps = [result[k] for k in ("install", "doctor", "rerun", "smoke")]
    if "unsupported" in steps:
        return "➖"
    if "fail" in steps:
        return "❌"
    if result.get("evidence") == "in-use":
        return "💻"
    # Every language has a smoke test, so a result without one predates it.
    return "❔" if result["smoke"] == "none" else "✅"


def checked_at(results: dict[str, dict], platform: str) -> str:
    """When a platform's results were last checked: the newest date, and the
    commit, when the results record it."""
    dates = sorted({(r["date"], (r.get("commit") or "")[:7]) for r in results.values() if r["platform"] == platform})
    if not dates:
        return "never"
    date, commit = dates[-1]
    return f"{date} at {commit}" if commit else date


def render_text(results: dict[str, dict]) -> str:
    """docs/coverage.md for these results."""
    languages = sorted(
        d for d in os.listdir(os.path.join(ROOT, "languages"))
        if os.path.isdir(os.path.join(ROOT, "languages", d)) and not d.startswith("_")
    )
    out = [
        "# Coverage",
        "",
        "Which languages' toolchains hecatron installs and checks on which",
        "platforms. Generated by `tests/coverage/matrix.py render` from",
        "`tests/coverage/results.json`; don't edit by hand. The coverage workflow",
        "(`.github/workflows/coverage.yml`) refreshes the results.",
        "",
        LEGEND,
        "",
        "Linux columns come from fresh Docker containers (`tests/docker/`) on",
        "GitHub's x86_64 and arm64 runners. macOS columns come from GitHub's macOS",
        "runners, which have many toolchains preinstalled (Go, Rust, Java, Node.js,",
        "Python...), so for those languages they show hecatron checking and",
        "reinstalling on such a machine rather than installing from nothing.",
        "",
        "| Language | " + " | ".join(name for _, name in PLATFORMS) + " |",
        "| --- |" + " :-: |" * len(PLATFORMS),
    ]
    for lang in languages:
        cells = [mark(results.get(f"{lang} {key}")) for key, _ in PLATFORMS]
        out.append(f"| {lang} | " + " | ".join(cells) + " |")
    symbols = [symbol for symbol, _ in MARKS]
    out += ["", "## Totals", "", "| Platform | " + " | ".join(symbols) + " |", "| --- |" + " --: |" * len(symbols)]
    for key, name in PLATFORMS:
        marks = [mark(results.get(f"{lang} {key}")) for lang in languages]
        out.append(f"| {name} | " + " | ".join(str(marks.count(symbol)) for symbol in symbols) + " |")
    # When each platform was checked: one line when a single run checked
    # them all, else one per platform.
    when = {name: checked_at(results, key) for key, name in PLATFORMS}
    if len(set(when.values())) == 1:
        out += ["", f"Last checked: {next(iter(when.values()))}."]
    else:
        out += ["", "Last checked:", ""] + [f"- {name}: {checked}" for name, checked in when.items()]
    return "\n".join(out) + "\n"


def render() -> None:
    with open(DOC, "w") as f:
        f.write(render_text(load()))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)
    c = sub.add_parser("collect")
    c.add_argument("--commit", default="")
    c.add_argument("logs", nargs="+")
    sub.add_parser("render")
    args = parser.parse_args()
    if args.command == "collect":
        collect(args.commit, args.logs)
    else:
        render()


if __name__ == "__main__":
    sys.exit(main())
