#!/usr/bin/env python3
"""Generate Dockerfile from per-language snippets.

Reads .hecatron/config/languages.json to determine active languages, then collects
apt packages and RUN/ENV blocks from .hecatron/languages/<lang>/dockerfile
snippets. Produces a single Dockerfile with deduplicated apt packages and
topologically sorted language blocks.

Usage:
    python3 .hecatron/tools/codegen/dockerfile.py           # generate
    python3 .hecatron/tools/codegen/dockerfile.py --check   # check for drift
"""

from __future__ import annotations

import json
import os
import sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from util import make_banner  # noqa: E402

# Always included regardless of active languages
BASE_PACKAGES = [
    "build-essential",
    "ca-certificates",
    "curl",
    "git",
    "gnupg",
    "unzip",
]


def load_active_languages() -> list[str]:
    """Return sorted list of active languages from config."""
    added_path = os.path.join(ROOT, ".hecatron", "config", "languages", "added.json")
    with open(added_path) as f:
        return sorted(json.load(f))


def parse_snippet(lang: str) -> tuple[list[str], list[str], str | None]:
    """Parse a language's dockerfile snippet.

    Returns (apt_packages, body_lines, after_constraint).
    - apt_packages: list of package names from # apt: directives
    - body_lines: all non-directive lines (RUN, ENV, comments, blanks)
    - after_constraint: language name from # after: directive, or None
    """
    snippet_path = os.path.join(
        ROOT, ".hecatron", "languages", lang, "dockerfile"
    )
    if not os.path.isfile(snippet_path):
        return [], [], None

    apt_packages: list[str] = []
    body_lines: list[str] = []
    after: str | None = None

    with open(snippet_path) as f:
        for line in f:
            stripped = line.rstrip("\n")
            if stripped.startswith("# apt:"):
                pkgs = stripped[len("# apt:"):].strip().split()
                apt_packages.extend(pkgs)
            elif stripped.startswith("# after:"):
                after = stripped[len("# after:"):].strip()
            else:
                body_lines.append(stripped)

    return apt_packages, body_lines, after


def has_body(lines: list[str]) -> bool:
    """Check if body lines contain any RUN/ENV instructions."""
    return any(
        line.startswith("RUN ") or line.startswith("ENV ")
        for line in lines
    )


def topological_sort(
    languages: list[str],
    after_map: dict[str, str | None],
    active_set: set[str],
) -> list[str]:
    """Sort languages respecting # after: constraints, falling back to alphabetical.

    Constraints referencing inactive languages are ignored.
    """
    # Build adjacency: lang must come after its dependency
    graph: dict[str, list[str]] = defaultdict(list)
    in_degree: dict[str, int] = {lang: 0 for lang in languages}

    for lang in languages:
        dep = after_map.get(lang)
        if dep and dep in active_set and dep in in_degree:
            graph[dep].append(lang)
            in_degree[lang] += 1

    # Kahn's algorithm with alphabetical tie-breaking
    queue = sorted(lang for lang in languages if in_degree[lang] == 0)
    result: list[str] = []

    while queue:
        current = queue.pop(0)
        result.append(current)
        for neighbor in sorted(graph[current]):
            in_degree[neighbor] -= 1
            if in_degree[neighbor] == 0:
                # Insert in sorted position
                idx = 0
                while idx < len(queue) and queue[idx] < neighbor:
                    idx += 1
                queue.insert(idx, neighbor)

    return result


def generate() -> str:
    """Generate the complete Dockerfile content."""
    active = load_active_languages()
    active_set = set(active)

    # Parse all snippets
    all_apt: list[str] = list(BASE_PACKAGES)
    body_map: dict[str, list[str]] = {}
    after_map: dict[str, str | None] = {}

    for lang in active:
        apt_pkgs, body, after = parse_snippet(lang)
        all_apt.extend(apt_pkgs)
        body_map[lang] = body
        after_map[lang] = after

    # Deduplicate and sort apt packages
    apt_packages = sorted(set(all_apt))

    # Filter to languages that have RUN/ENV blocks
    langs_with_body = [lang for lang in active if has_body(body_map[lang])]

    # Topological sort for emit order
    sorted_langs = topological_sort(langs_with_body, after_map, active_set)

    # Build output
    lines: list[str] = []

    # Banner
    banner = make_banner([
        "Generated by .hecatron/tools/codegen/dockerfile.py",
        "from snippets in .hecatron/languages/*/dockerfile",
        "",
        "To regenerate: just dockerfile",
        "Regenerated automatically by: just add / just remove",
    ])
    lines.append(banner.rstrip("\n"))
    lines.append("")

    # FROM
    lines.append("FROM ubuntu:24.04")
    lines.append("")
    lines.append('ENV DEBIAN_FRONTEND=noninteractive')
    lines.append("")

    # Apt batch install
    lines.append("# System packages + language runtimes available from distro")
    lines.append("RUN apt-get update && apt-get install -y --no-install-recommends \\")
    for pkg in apt_packages:
        lines.append(f"    {pkg} \\")
    lines.append("    && rm -rf /var/lib/apt/lists/*")
    lines.append("")

    # Language-specific RUN/ENV blocks
    for lang in sorted_langs:
        body = body_map[lang]
        # Strip leading/trailing blank lines from body
        while body and body[0] == "":
            body.pop(0)
        while body and body[-1] == "":
            body.pop()
        if body:
            for line in body:
                lines.append(line)
            lines.append("")

    # just (task runner) — always included
    lines.append("# just (task runner)")
    lines.append(
        "RUN curl --proto '=https' --tlsv1.2 -sSf https://just.systems/install.sh"
        " | bash -s -- --to /usr/local/bin"
    )
    lines.append("")
    lines.append("WORKDIR /workspace")
    lines.append("")
    lines.append('CMD ["bash"]')
    lines.append("")

    return "\n".join(lines)


def main() -> None:
    check = "--check" in sys.argv

    content = generate()
    dockerfile_path = os.path.join(ROOT, "age", "Dockerfile")

    if check:
        if os.path.isfile(dockerfile_path):
            with open(dockerfile_path) as f:
                existing = f.read()
            if existing == content:
                print("Dockerfile is up to date.")
                sys.exit(0)
            else:
                print("Dockerfile is out of date. Run 'just dockerfile' to regenerate.")
                sys.exit(1)
        else:
            print("Dockerfile does not exist. Run 'just dockerfile' to generate.")
            sys.exit(1)
    else:
        with open(dockerfile_path, "w") as f:
            f.write(content)
        print(f"Generated {dockerfile_path}")


if __name__ == "__main__":
    main()
