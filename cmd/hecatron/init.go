// init is `hecatron init [dir] [--components a,b] [--impl-path TEMPLATE]
// [--languages a,b] [--justfile] [--force] [--no-agents]`, as manage.py's
// cmd_init: detect the repository's languages and layout, write
// .hecatron/config.json, the .gitignore entries, and hecatron's section in
// AGENTS.md.

const justfile = `# Recipes delegating to hecatron (generated by: hecatron init --justfile).
# Import from the project justfile with: import '.hecatron/hecatron.just'

test *args:
    hecatron test {{args}}

lint *args:
    hecatron lint {{args}}

build *args:
    hecatron build {{args}}

clean *args:
    hecatron clean {{args}}

doctor *args:
    hecatron doctor {{args}}

install *args:
    hecatron install {{args}}
`

const (
	agentsBegin = "<!-- hecatron:begin -->"
	agentsEnd   = "<!-- hecatron:end -->"
)

// agentsSection is what init writes into AGENTS.md: short, since agents
// load it every session, and nothing about the project's languages, which
// would go stale.
const agentsSection = agentsBegin + `
## Building and testing (hecatron)

This repository uses [hecatron](https://github.com/dnf/hecatron): the same
commands for every language. ` + "`hct help agents`" + ` is a compact reference.

- Start with ` + "`hct status`" + `: each language, its toolchain, its last runs and
  what changed, and what to run next.
- ` + "`hct test`, `hct lint`, `hct build`" + `: every language; name one to run only
  it (` + "`hct test go`" + `). ` + "`hct format`" + ` fixes formatting; ` + "`hct deps`" + ` fetches
  dependencies.
- Exit status 0 passed, 1 failed. Each language's log is in
  ` + "`{logs}/<action>/<language>.log`" + `.
- Ask before ` + "`hct install` or `hct doctor --fix`" + `: they install toolchains
  on this machine. ` + "`hct doctor`" + ` alone only checks.
- To change how a language is built or tested, write
  ` + "`.hecatron/languages/<lang>/<action>.sh`" + `.
` + agentsEnd + "\n"

func (c *cli) init() (int, bool) {
	args, ok := parseManageArgs(c.args, []string{"--justfile", "--force", "--no-agents"},
		[]string{"--components", "--impl-path", "--languages"}, 1)
	if !ok {
		return 0, false
	}
	dir := "."
	if len(args.positionals) == 1 {
		dir = args.positionals[0]
	}
	root := dir
	if !filepath.IsAbs(root) {
		cwd, err := workingDir()
		if err != nil {
			return 0, false
		}
		root = project.PyJoin(cwd, dir)
	}
	root = cleanAbs(root)
	git := exec.Command("git", "rev-parse", "--show-toplevel")
	git.Dir = root
	if git.Run() != nil {
		return (&manageFailure{root + " is not inside a git repository", 1}).report(), true
	}
	configPath := project.PyJoin(root, ".hecatron", "config.json")
	if info, err := os.Stat(configPath); err == nil && info.Mode().IsRegular() && !args.flags["--force"] {
		fmt.Printf("%s already exists (use --force to overwrite).\n", relativeToWorkingDir(configPath))
		return 0, true
	}
	config, notAdded, err := project.DetectedConfig(root, c.home, args.values["--components"],
		args.values["--impl-path"], args.values["--languages"])
	if err != nil {
		return 0, false
	}
	configText, err := project.PyJSON(config)
	if err != nil {
		return 0, false
	}
	agents, err := agentInstructions(root, ".logs")
	if err != nil {
		return 0, false
	}
	if err := os.MkdirAll(filepath.Dir(configPath), 0o777); err != nil {
		return c.writeFailed(&strings.Builder{}, err), true
	}
	if err := os.WriteFile(configPath, []byte(configText+"\n"), 0o666); err != nil {
		return c.writeFailed(&strings.Builder{}, err), true
	}
	if err := project.IgnoreProjectFiles(root); err != nil {
		return c.writeFailed(&strings.Builder{}, err), true
	}
	if args.flags["--justfile"] {
		if err := os.WriteFile(project.PyJoin(root, ".hecatron", "hecatron.just"), []byte(justfile), 0o666); err != nil {
			return c.writeFailed(&strings.Builder{}, err), true
		}
	}
	var agentFiles []string
	if !args.flags["--no-agents"] {
		if agentFiles, err = agents.write(); err != nil {
			return c.writeFailed(&strings.Builder{}, err), true
		}
	}
	languages := configStrings(config, "languages")
	components := configStrings(config, "components")
	if components == nil {
		components = []string{"."}
	}
	implPath, _ := config.Get("implPath")
	var out strings.Builder
	fmt.Fprintf(&out, "Initialised %s\n", root)
	languageList := strings.Join(languages, ", ")
	if languageList == "" {
		languageList = "(none detected; add with hecatron add <lang>)"
	}
	fmt.Fprintf(&out, "  languages:  %s\n", languageList)
	fmt.Fprintf(&out, "  components: %s   implPath: %s\n", strings.Join(components, ", "), implPath)
	if implPaths, ok := config.Values["implPaths"].(*project.Object); ok {
		for _, lang := range implPaths.Keys {
			fmt.Fprintf(&out, "  %s lives in %s (implPaths)\n", lang, implPaths.Values[lang])
		}
	}
	var reasons []string
	for lang := range notAdded {
		reasons = append(reasons, lang)
	}
	sort.Strings(reasons)
	for _, lang := range reasons {
		fmt.Fprintf(&out, "  not added: %s (%s)\n", lang, notAdded[lang])
	}
	if len(agentFiles) > 0 {
		fmt.Fprintf(&out, "  instructions for AI agents: %s (--no-agents to skip)\n", strings.Join(agentFiles, ", "))
	}
	out.WriteString("Next: hecatron doctor   (checks each language's toolchain)\n")
	fmt.Print(out.String())
	return 0, true
}

// cleanAbs is Python's os.path.abspath's normalisation of an absolute
// path.
func cleanAbs(path string) string {
	cleaned := filepath.Clean(path)
	if strings.HasPrefix(path, "//") && !strings.HasPrefix(path, "///") {
		return "/" + cleaned
	}
	return cleaned
}

func configStrings(config *project.Object, key string) []string {
	list, ok := config.Values[key].([]any)
	if !ok {
		return nil
	}
	result := make([]string, 0, len(list))
	for _, item := range list {
		result = append(result, fmt.Sprint(item))
	}
	return result
}

// agentEdits are the changes write_agent_instructions makes, worked out
// before any is made.
type agentEdits struct {
	agentsPath, agents string // "" when AGENTS.md is current
	claudePath, claude string // what to append to CLAUDE.md, "" for nothing
}

// agentInstructions is manage.py's write_agent_instructions, planned:
// hecatron's section in AGENTS.md (replacing an earlier one), and an
// existing CLAUDE.md made to load AGENTS.md.
func agentInstructions(root, logs string) (agentEdits, error) {
	section := strings.ReplaceAll(agentsSection, "{logs}", logs)
	var edits agentEdits
	path := project.PyJoin(root, "AGENTS.md")
	text := ""
	if isRegularFile(path) {
		var err error
		if text, err = project.ReadPyText(path); err != nil {
			return edits, err
		}
	}
	var updated string
	if strings.Contains(text, agentsBegin) && strings.Contains(text, agentsEnd) {
		start := strings.Index(text, agentsBegin)
		end := strings.Index(text, agentsEnd) + len(agentsEnd)
		_, size := utf8.DecodeRuneInString(text[end:])
		end += max(size, 1) // the character after the marker: its newline
		updated = pySlice(text, 0, start) + section + pySlice(text, end, len(text))
	} else {
		updated = text
		if text != "" && !strings.HasSuffix(text, "\n") {
			updated += "\n"
		}
		if text != "" {
			updated += "\n"
		}
		updated += section
	}
	if updated != text {
		edits.agentsPath, edits.agents = path, updated
	}
	claude := project.PyJoin(root, "CLAUDE.md")
	if isRegularFile(claude) {
		text, err := project.ReadPyText(claude)
		if err != nil {
			return edits, err
		}
		// CLAUDE.md read after AGENTS.md is written: a link to it (Pulumi's)
		// already holds the section.
		if sameFile(claude, path) {
			text = updated
		}
		if !strings.Contains(text, "@AGENTS.md") && !strings.Contains(text, agentsBegin) {
			separator := ""
			if text != "" && !strings.HasSuffix(text, "\n") {
				separator = "\n"
			}
			edits.claudePath, edits.claude = claude, separator+"\n@AGENTS.md\n"
		}
	}
	return edits, nil
}

// pySlice is Python's text[start:end] for byte offsets within text.
func pySlice(text string, start, end int) string {
	start, end = min(max(start, 0), len(text)), min(max(end, 0), len(text))
	if start >= end {
		return ""
	}
	return text[start:end]
}

// write makes the edits and returns the files changed.
func (e agentEdits) write() ([]string, error) {
	var changed []string
	if e.agentsPath != "" {
		if err := os.WriteFile(e.agentsPath, []byte(e.agents), 0o666); err != nil {
			return nil, err
		}
		changed = append(changed, "AGENTS.md")
	}
	if e.claudePath != "" {
		f, err := os.OpenFile(e.claudePath, os.O_APPEND|os.O_WRONLY, 0o666)
		if err != nil {
			return changed, err
		}
		_, err = f.WriteString(e.claude)
		if closeErr := f.Close(); err == nil {
			err = closeErr
		}
		if err != nil {
			return changed, err
		}
		changed = append(changed, "CLAUDE.md")
	}
	return changed, nil
}

func sameFile(a, b string) bool {
	infoA, errA := os.Stat(a)
	infoB, errB := os.Stat(b)
	return errA == nil && errB == nil && os.SameFile(infoA, infoB)
}

func isRegularFile(path string) bool {
	info, err := os.Stat(path)
	return err == nil && info.Mode().IsRegular()
}
